PLAYER VERSUS PVP

    • Players will no longer be affected by knockback effects while under the
      effects of Fear and Disorient crowd control.
    • Gladiator's Distinction (PvP Trinket Set Bonus) now increases primary stat by
      15% (was 12%) and Stamina by 5% (was 10%) for tank and damage dealer roles.
    • Gladiator's Distinction (PvP Trinket Set Bonus) now increases Stamina by 10%
      (was 15%) for the healer role.
    • BATTLEGROUNDS
      > Developers' notes: We've observed player survivability in battlegrounds
        making combat less enjoyable, so we're making a change to reduce healing
        received which should allow for healers and off-healing abilities to be
        less powerful.
      > Players will now receive 20% less healing in Battlegrounds.
    • SOLO SHUFFLE AND BATTLEGROUND BLITZ
      > To reduce win trading and queue manipulation, now when a player misses a
        Solo Shuffle or Battleground Blitz queue, a 1-minute debuff prevents
        further queueing. The debuff stacks for consecutive missed queues within a
        window of time and is account-wide.
    • Spoils of War will grant 50% increased Conquest once Conquest has been
      uncapped for the season (was 30%).
      > Developers' notes: We would like to speed up gearing for players who are
        participating late in the PvP season, so we are increasing Conquest gains
        from Spoils of War.
    • Developers' notes: In Curse of Ula'tek, we've decided to reduce the
      effectiveness of a large number of movement speed reductions in PvP. We have
      found in the past that when players have access to strong snares with a high
      uptime, there are less opportunities for enemies to use positioning and
      escape tactics. Our primary target has been strong snares that are auto
      applied during normal combat rotations, with some of the activated reductions
      retaining their strength. In general, we've reduced movement speed reductions
      a tier down, with 70% reduced to 50%, 50% to 30%, and so on.

