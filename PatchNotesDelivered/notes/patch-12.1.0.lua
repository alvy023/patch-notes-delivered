HOUSING UPDATES

MAKE THE MOST OF HOUSING WITH BLUEPRINTS

For players who want to share their cool builds with others, you'll be able to export
the entirety of your exterior and your interior, or your interior, your exterior, or a
single room alone as you like.

[[img:21]]

[[img:22]]

    • Blueprints let players save their housing creations to swap between or share
      them with other players!
    • Blueprint codes can be shared cross-region (excluding China) with other
      players for them to import as well.
    • Blueprints operate on the entire house (both inside and out), the interior
      only, the exterior only, or a single room.
    • When importing, a list of all required rooms and decor will be shown,
